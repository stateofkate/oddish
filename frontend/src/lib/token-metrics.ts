import type { TaskEffortSummary } from "./types";

export const TOKEN_METRICS = [
  { value: "total", label: "Total", field: "tokens", sort: "avg_tokens", description: "Input + output. Cached input is already included." },
  { value: "uncached_input", label: "Uncached input", field: "uncached_input_tokens", sort: "avg_uncached_input_tokens", description: "Input not served from cache, including cache writes." },
  { value: "cached_input", label: "Cached input", field: "cached_input_tokens", sort: "avg_cached_input_tokens", description: "Input served from cache. Missing cache measurements are excluded." },
  { value: "output", label: "Output", field: "output_tokens", sort: "avg_output_tokens", description: "Tokens generated by the model." },
] as const;
export type TokenMetric = typeof TOKEN_METRICS[number];
export type EffortMetric = "steps" | TokenMetric["field"];

export function selectedTokenMetric(params: Pick<URLSearchParams, "get">): TokenMetric {
  const sort = params.get("sort")?.replace(/_(asc|desc)$/, "");
  return TOKEN_METRICS.find(metric => metric.sort === sort)
    ?? TOKEN_METRICS.find(metric => metric.value === params.get("token_metric"))
    ?? TOKEN_METRICS[0];
}

export function setTokenMetric(params: URLSearchParams, value: string): boolean {
  const metric = TOKEN_METRICS.find(option => option.value === value) ?? TOKEN_METRICS[0];
  const sort = params.get("sort") ?? "";
  const sorted = TOKEN_METRICS.some(option => sort.replace(/_(asc|desc)$/, "") === option.sort);
  if (metric.value === "total") params.delete("token_metric");
  else params.set("token_metric", metric.value);
  if (sorted) {
    params.set("sort", `${metric.sort}_${sort.endsWith("_asc") ? "asc" : "desc"}`);
    params.delete("offset");
  }
  return sorted;
}

export function effortMeasurement(effort: TaskEffortSummary | undefined, metric: EffortMetric) {
  const count = effort?.[`${metric}_trial_count`] ?? 0;
  const sum = effort?.[`${metric}_sum`];
  return { count, average: count > 0 && sum != null ? sum / count : null };
}
